/// Текущая версия протокола.
///
/// Увеличивается при **несовместимых** изменениях формата.
/// При изменении: обязательно обновить `codec::MIN_SUPPORTED_VERSION`,
/// если старая версия больше не поддерживается.
pub const PROTOCOL_VERSION: u8 = 1;

/// Минимальная версия протокола, которую мы понимаем.
/// Пакеты с версией меньше этой отклоняются.
pub const MIN_SUPPORTED_VERSION: u8 = 1;

/// Максимальный размер одного пакета (защита от переполнения памяти).
/// 16 MB — с запасом для больших сообщений и медиа-чанков в будущем.
pub const MAX_PACKET_SIZE: usize = 16 * 1024 * 1024;

// ═══════════════════════════════════════════════════════════════════
// ОБЩИЙ РЕЗУЛЬТАТ
// ═══════════════════════════════════════════════════════════════════

/// Результат операций Wire Protocol.
pub type ProtocolResult<T> = Result<T, ProtocolError>;

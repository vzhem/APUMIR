//! # Wire Protocol — формат сообщений между узлами
//!
//! Определяет **всё**, что узлы отправляют друг другу по сети:
//!
//! - **messages** — типы сообщений (текст, ack, handshake, DHT, presence, relay)
//! - **codec**    — сериализация в байты (через bincode) + версионирование
//!
//! ## Двухуровневая структура пакета:
//!
//! ```text
//! ┌────────────────────────────────────────────────────────────┐
//! │              СЕТЕВОЙ ПАКЕТ (то что летит по QUIC)           │
//! ├────────┬───────────────────────────────────────────────────┤
//! │  Ver   │           Serialized ProtocolMessage               │
//! │ (1 б)  │              (bincode-кодированный)                │
//! └────────┴───────────────────────────────────────────────────┘
//! ```
//!
//! - **Ver** — версия протокола (1 байт). Первым, чтобы можно было
//!   отклонить несовместимую версию не парся всё сообщение.
//! - **ProtocolMessage** — enum со всеми возможными типами.
//!
//! ## Использование:
//!
//! ```ignore
//! use crate::protocol::{codec, messages::ProtocolMessage, messages::TextMsg};
//!
//! // Отправка
//! let msg = ProtocolMessage::Text(TextMsg { ... });
//! let bytes: Vec<u8> = codec::encode(&msg)?;
//! quic_stream.write(&bytes).await?;
//!
//! // Приём
//! let bytes = quic_stream.read().await?;
//! let msg: ProtocolMessage = codec::decode(&bytes)?;
//! match msg {
//!     ProtocolMessage::Text(t) => { ... }
//!     ProtocolMessage::Ack(a) => { ... }
//!     ...
//! }
//! ```

pub mod codec;
pub mod messages;

// ═══════════════════════════════════════════════════════════════════

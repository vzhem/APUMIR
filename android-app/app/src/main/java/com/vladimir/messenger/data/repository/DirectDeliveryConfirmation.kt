package com.vladimir.messenger.data.repository

import com.vladimir.messenger.data.RustBridge

/**
 * Прямая доставка закрыла задачу — снимаем резервные обязательства.
 *
 * Зачем отдельный файл: `ChatRepository.kt` — god-файл под храповиком строк
 * (`scripts/ci/check-god-files.py`), поэтому вызов живёт здесь, а рассуждение
 * о том, зачем он нужен, — рядом, где ему место.
 *
 * Владелец 2026-11-15: «если я общаюсь в чате на прямую и сообщение сразу
 * доходит, то оно не должно больше никому слаться для резервных копий — оно
 * сразу доставилось и задача выполнилась».
 *
 * Раньше снятие удержания звал только путь квитанции доставки
 * (`routeOutgoingDeliveryAck` → `confirmMessageDelivered`). Прямой успех до
 * него не доходил, поэтому строка, доставленная напрямую, могла ещё долго
 * предлагаться соседям и брокеру: ядро пере-предлагает своё недоставленное
 * каждые полминуты, а снять его было некому.
 *
 * Звёздочка не нужна: ядро снимает удержание и на своей стороне, в момент
 * успешной прямой отправки. Этот вызов — страховка для путей, где строка
 * уходила раньше (легла в очередь, пока прямого пути не было) и дошла уже
 * отсюда.
 */
internal fun confirmDirectDelivery(messageId: String) {
    RustBridge.confirmMessageDelivered(messageId)
}

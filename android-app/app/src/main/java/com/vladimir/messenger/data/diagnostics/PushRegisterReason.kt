package com.vladimir.messenger.data.diagnostics

/**
 * Почему последняя попытка зарегистрировать маршрут пробуждения закончилась
 * так, а не иначе.
 *
 * Зачем отдельный перечень. Раздел `[push]` печатал только `фаза=failed`, и по
 * отчёту с телефона это читалось тремя способами сразу: «служба отвергла
 * операцию», «сеть не пускает» и «ключ обмена не готов». Лечатся они совсем
 * по-разному, а подсказка в отчёте перечисляла все три сразу — то есть не
 * отвечала ни на один. Владелец ждал буждения друзей часами, и каждый новый
 * отчёт без причины возвращал разбор к началу.
 *
 * Приватность: только фиксированное имя и неизменная подсказка. Ни маршрута,
 * ни токена, ни идентификатора собеседника, ни текста исключения сюда не
 * попадает — снимок остаётся таким же безопасным, как был.
 */
enum class PushRegisterReason(val hint: String) {
    /** Попытка ещё не делалась, или причина не записана. */
    NONE("причина не записана"),

    /** Поставщик не выдал токен: нет служб Google, сборка не настроена, запрос упал. */
    TOKEN_UNAVAILABLE("токен от поставщика не получен"),

    /** Журнал токена не прочитан или не перезаписан. */
    JOURNAL_UNAVAILABLE("журнал токена недоступен"),

    /** Список собеседников не прочитан целиком: на неполном наборе регистрировать нельзя. */
    TARGETS_UNREADABLE("список собеседников не прочитан"),

    /** Ни одного закреплённого собеседника: регистрировать некого. */
    NO_PINNED_PEERS("закреплённых собеседников нет"),

    /** Пара не готова к подписи: нет закрепления, секрета обмена или записи регистрации. */
    PEER_NOT_READY("пара не готова: нет закрепления, секрета обмена или записи"),

    /** Операция не принята: не прошла проверку полей или подписи, либо служба отказала. */
    REQUEST_INVALID("операция не принята: проверка полей, подписи или отказ службы"),

    /** Служба считает операцию устаревшей (номер последовательности уже израсходован). */
    SERVER_STALE("служба считает операцию устаревшей"),

    /** Служба ограничила частоту обращений. */
    SERVER_THROTTLED("служба ограничила частоту обращений"),

    /** Служба недоступна, не ответила или ответила ошибкой. */
    SERVER_UNAVAILABLE("служба недоступна или не ответила"),

    /** Локальное хранилище регистрации отказало. */
    STORAGE_UNAVAILABLE("локальное хранилище регистрации отказало"),

    /** Маршрут зарегистрирован: это не отказ, а штатный итог. */
    REGISTERED("маршрут зарегистрирован"),
}

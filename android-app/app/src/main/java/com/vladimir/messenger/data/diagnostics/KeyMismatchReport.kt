package com.vladimir.messenger.data.diagnostics

/**
 * «Ключ собеседника не совпал» — где именно.
 *
 * Вынесено из `DiagnosticsReport.kt` по правилу god-файлов (AGENTS.md п. 8).
 *
 * Зачем отдельная строка. В отчёте с телефона от 2026-11-14 стояло: «смена ключа
 * у собеседника — 10 раз · подписанный HELLO не совпал с закреплённым ключом,
 * проверьте личность перед обновлением QR», и рядом — «часть сообщений при этом
 * вскрылась» и «работает подпись и обмен». Человек читает это как «меня
 * подменяют» и не понимает, почему часть сообщений всё же доходит.
 *
 * Причина расхождения бывает на двух РАЗНЫХ дорогах:
 *  - `HELLO` — не сошёлся ключ ОБМЕНА (X25519). Именно он нужен для закрепления
 *    пары, прямого пути и зашифрованного запроса ранга, то есть для значка VIP;
 *  - `opened` — не сошёлся ключ, взятый из уже ВСКРЫТОГО сообщения. Тут ключ
 *    подписи рабочий (сообщения вскрываются), а расходится только дорога обмена.
 *
 * Разные дороги — разные действия: в первом случае нужен повторный QR, во
 * втором достаточно честно сказать, что переписка идёт, а обмен ключами — нет.
 */
internal fun StringBuilder.appendKeyMismatch(facts: DiagnosticsFacts) {
    val hello = facts.helloKeyMismatch ?: 0L
    val opened = facts.openedKeyMismatch ?: 0L
    if (hello > 0L || opened > 0L) {
        appendLine(
            "  ↳ где поймано: ключ обмена (HELLO)=$hello, " +
                "ключ из вскрытого сообщения=$opened",
        )
    }
    if (facts.peerKeyChangedAtMs <= 0L) return
    appendLine(
        "  ↳ подписанный HELLO не совпал с закреплённым ключом; проверьте " +
            "личность собеседника вне приложения перед обновлением QR",
    )
    if (opened > 0L && hello == 0L) {
        // Сообщения открываются, а путь обмена ключами расходится: это не
        // «собеседник подменён», а поломка отдельной дороги.
        appendLine(
            "  ↳ сообщения при этом вскрываются — расходится только ключ обмена; " +
                "QR сбрасывать не нужно",
        )
    }
}

package com.vladimir.messenger.data.mlkit

import android.util.Log

/**
 * Разрешение на инициализацию ML Kit: только в процессе, где уже был экран.
 *
 * Зачем запрет. ML Kit поднимает себя через собственный ContentProvider
 * (`MlKitInitProvider`) в момент установки провайдеров. Если процесс успел
 * инициализировать ML Kit сам — переводом, фильтрами лица или вырезанием фона, —
 * а Android ставит этот провайдер ПОЗЖЕ, приложению приходит
 * `IllegalStateException: MlKitContext is already initialized` из
 * `ActivityThread.installProvider`, и процесс умирает целиком. В отчёте это
 * `reason=crash` и `MlKitInitProvider`, и именно так теряется входящий сигнал:
 * телефон поднимает процесс ради доставки, а тот умирает на провайдерах ещё до
 * обработчика сигнала.
 *
 * Лечение без опоры на внутренности библиотеки: процесс, который поднят фоном
 * (задача, сигнал, служба) и ни разу не показывал экран, ML Kit не трогает.
 * Тогда установка провайдеров всегда первая, и гонки не существует. На экране
 * всё работает как раньше: провайдеры установлены задолго до первого кадра, и
 * отказ виден только там, где ML Kit всё равно нечего показывать.
 */
internal object MlKitGate {

    /** Ставится первым же показанным экраном ЭТОГО процесса. */
    @Volatile
    private var screenSeen = false

    /** Активность показана: с этого момента ML Kit поднимать безопасно. */
    fun noteScreen() {
        screenSeen = true
    }

    /**
     * Можно ли трогать ML Kit в этом процессе.
     *
     * Значение только растёт: процесс, где экран был, остаётся «с экраном» и
     * после сворачивания — там провайдеры уже установлены, повторной установки
     * не будет.
     */
    fun mayInitialise(): Boolean = screenSeen

    /** Одна строка в logcat: функция ML не поднялась и почему. */
    fun refusal(tag: String, feature: String) {
        Log.w(tag, "$feature skipped: no screen in this process, ML Kit init stays deferred")
    }
}

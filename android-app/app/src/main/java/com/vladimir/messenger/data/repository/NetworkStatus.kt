package com.vladimir.messenger.data.repository

/**
 * Состояние связи для человека.
 *
 * [Relayed] появилось не «для красоты»: ядро умеет доставлять письма через
 * relay-сессию брокера, когда прямого подписанного соседа нет, и именно так
 * работает большинство телефонов в мобильной сети. Пока такого состояния в
 * перечислении не было, интерфейс показывал вечное «Подключение…» - хотя
 * сообщения и файлы в это время доходили (жалоба владельца 2026-10-28).
 */
enum class NetworkStatus {
    /** Прямой канал с подписанным соседом. */
    Connected,

    /** Связи нет, идёт попытка подключиться. */
    Connecting,

    /**
     * Связь есть, но только через relay/брокер: письма идут, прямого соседа
     * нет. Это рабочее состояние, а не поломка.
     */
    Relayed,

    /** Связь есть, но часть пути недоступна (прямой канал не поднялся). */
    Degraded,

    /** Никакой связи. */
    Disconnected,
}

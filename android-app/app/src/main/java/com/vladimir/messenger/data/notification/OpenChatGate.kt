package com.vladimir.messenger.data.notification

/**
 * Какой чат человек читает прямо сейчас.
 *
 * Зачем. Владелец 2026-11-18: «пишешь сообщение, проходит пара секунд и
 * происходит моргание». Причина — плашка-уведомление: она появляется поверх
 * экрана на КАЖДОЕ входящее, даже когда этот чат открыт, а с v11.74.533 её канал
 * громкий (звук и вибрация). Человек смотрит переписку, отвечает — и получает
 * всплывающее окно с уже прочитанным сообщением, которое гасит и снова
 * подсвечивает экран.
 *
 * Правило: если открыт именно этот чат И приложение на экране, уведомление не
 * нужно — сообщение уже видно в переписке. В фоне (свёрнуто, другой экран)
 * уведомление обязательно: иначе входящее потеряется.
 *
 * Состояние намеренно в памяти процесса: после перезапуска оно неизвестно, а
 * «неизвестно» должно вести себя как «чат не открыт», то есть уведомление
 * показывается.
 */
object OpenChatGate {

    @Volatile
    private var openChatId: String? = null

    /** Экран чата показан. */
    fun opened(chatId: String) {
        if (chatId.isNotBlank()) openChatId = chatId
    }

    /** Экран чата закрыт; чужой идентификатор не сбрасывает текущий. */
    fun closed(chatId: String) {
        if (openChatId == chatId) openChatId = null
    }

    /**
     * Стоит ли молчать про это сообщение.
     *
     * @param appInForeground приложение на экране (см. `DeliveryCadence`).
     */
    fun isReading(chatId: String, appInForeground: Boolean): Boolean =
        appInForeground && chatId.isNotBlank() && openChatId == chatId
}

package com.vladimir.messenger.data.local.entity

import androidx.room.Entity

/**
 * Закреплённый ключ подписи постов (рой, этап 1; схема 19).
 *
 * Манифест поста несёт открытый ключ подписанта, но сам по себе ключ ничего
 * не доказывает - его надо привязать к узлу. Привязка берётся из двух
 * источников, и оба опираются на подлинность отправителя пакета в ядре:
 *  - сам узел прислал манифест или `pkeys` со своим ключом (`attestedBy` =
 *    он сам);
 *  - владелец канала прислал `pkeys` с ключами своих администраторов
 *    (`attestedBy` = владелец).
 *
 * Строки хранятся по паре «узел + кто заверил»: ключ, заверенный владельцем
 * канала А, не годится в канале Б с другим владельцем - иначе чужой владелец
 * мог бы «назначить» узлу свой ключ и подделывать его посты в других каналах.
 */
@Entity(
    tableName = "post_signers",
    primaryKeys = ["nodeId", "attestedBy"],
)
data class PostSignerEntity(
    val nodeId: String,
    val attestedBy: String,
    /** base64url открытого ключа Ed25519 (32 байта). */
    val publicKey: String,
    val updatedAtMs: Long,
)

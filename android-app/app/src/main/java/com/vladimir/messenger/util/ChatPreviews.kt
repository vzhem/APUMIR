package com.vladimir.messenger.util

/**
 * Раунд 155: человекочитаемые предпросмотры для списков чатов и тем -
 * служебные строки не должны светиться буквами и цифрами на главной
 * (владелец, скрин 2026-09-24: «APUGIFREF1|b11…» у группы, «APUSTK1|ask»
 * в личном чате, «🖼 39513698-…» у файловой визитки).
 *
 * Внутри чата всё рендерится как надо (карточка гифки и т.п.), чистим
 * ТОЛЬКО предпросмотры: список чатов, список тем, поиск.
 */
object ChatPreviews {

    private const val GIF_LABEL = "\uD83D\uDDBC Гифка"

    /** Файловая визитка с uuid-именем: «🖼 39513698-… (1.2 МБ)». */
    private val UUID_FILE = Regex(
        "^\uD83D\uDDBC\\s+[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}" +
            "-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}.*"
    )

    /**
     * Раунд 156: служебные конверты роя (каталог стикеров APUSTK1 и
     * провод гифок APUGIF1 - миниатюры/порции) - НЕ сообщения: не должны
     * звонить в уведомлениях и накручивать непрочитанные (решение
     * владельца). Ссылки APUGIFREF1 - настоящие сообщения-карточки, их
     * не трогаем.
     */
    fun isServiceEnvelope(raw: String?): Boolean {
        if (raw == null) return false
        val t = raw.trim()
        return t.startsWith("APUSTK1|") || t.startsWith("APUGIF1|") || t.startsWith("APUTYP1|")
    }

    /**
     * р239/р247: служебный пакет приложения, которому в переписке не место.
     * ACK v140 ходит обычным P2P-пакетом, поэтому фильтруется отдельно от
     * маршрутизаторов транспорта; это последний страж перед записью в Room.
     *
     * Список шире, чем [isServiceEnvelope]: страховка на самом сохранении
     * сообщения (ChatRepository.saveIncomingMessage). Живой пример ошибки:
     * r235 поставил разбор «печатает…» только в резервный путь приёма, и
     * пакет APUTYP1|1 лёг в чат сообщением с уведомлением (владелец, 30.09).
     * Карточки-сообщения (ссылка на гифку, «переслано») здесь НЕ перечислены -
     * это настоящие сообщения.
     */
    private val SERVICE_PACKETS = listOf(
        "ack|",          // подтверждение доставки (r243), страховка от утечки (r247)
        "APUTYP1|",      // «печатает…» (r235)
        "APUSTK1|",      // рой стикеров
        "APUGIF1|",      // провод гифок
        "APUCALL1|",     // звонковая сигнализация
        "APUCALLHS1|",   // завершение звонка
        "APUDEL1|",      // «удали у всех»
        "APUDELQ1|",     // очередь удаления
        "APUREACT1|",    // реакции
        "APUREAD1|",     // «прочитано»
        "APUHEART1|",    // сердечки профиля
        "APUVIEW1|",     // просмотры постов
        "APUGRP1|",      // групповые конверты
        "APUDMR1|",      // цитаты-ответы личных сообщений
        "APUBSP1|",      // рассылка поста
        "APUUDP01|",     // обнаружение устройств в сети
        "APUMIR1|",      // зеркальные кадры, попавшие в поток сообщений
        "APUBAK1|",      // копия азбуки адресов
        "APUREF1|",      // реферальная атрибуция
        "APUSEAL1|",     // конверт (не вскрылся - значит, не нам)
    )

    /** Служебный пакет? true - сохранять его как сообщение нельзя. */
    fun isServicePacket(raw: String?): Boolean {
        if (raw == null) return false
        val t = raw.trim()
        // Ранг собеседника проверяем ДО общего списка: конверт едет в обёртке
        // «печатает…», а это чужой префикс - если обёртка когда-нибудь сменится,
        // служебная строка всё равно не останется в переписке.
        if (com.vladimir.messenger.data.rank.RankWire.isRankPacket(t)) return true
        // В v140+ ACK идёт по прямому каналу в формате обычного сообщения;
        // этот общий страж закрывает путь, который пропустил транспортный разборщик.
        return SERVICE_PACKETS.any { t.startsWith(it) }
    }

    /**
     * Служебная строка -> короткая человеческая подпись; обычный текст
     * возвращается как был (null проходит насквозь).
     */
    fun human(raw: String?): String? {
        if (raw == null) return null
        val t = raw.trim()
        // Ссылка на гифку (раунд 128): «APUGIFREF1|<sha256>».
        // Раунд 203: пересылка - шапка-источник вместо служебной строки.
        if (t.startsWith("APUFWD1|")) {
            ForwardMarker.parseRef(t)?.let { return "↩ Переслано из «" + it.label + "»" }
        }
        if (t.startsWith("APUGIFREF1|")) return GIF_LABEL
        // Ранг собеседника (р246): едет в обёртке «печатает…», поэтому проверяем
        // его раньше - иначе в предпросмотре стояло бы чужое «печатает…».
        if (com.vladimir.messenger.data.rank.RankWire.isRankPacket(t)) return "знак VIP"
        // «Печатает…» (р235/р239): строка мимолётная, в списке чатов её быть
        // не должно - показываем человеческое слово.
        if (t.startsWith("APUTYP1|")) return "печатает…"
        // Конверт стикер-роя (раунд 139): «APUSTK1|ask|…».
        if (t.startsWith("APUSTK1|")) return "Стикеры"
        // Раунд 165: визитка стикера в группе/канале (имя «Стикер…») -
        // «🖼 Стикер» вместо sha/имени в уведомлениях и списках.
        GroupFileMarker.parse(t)?.let { info ->
            if (info.displayName.startsWith("Стикер")) return "\uD83D\uDDBC Стикер"
        }
        // Визитка файла с uuid-именем (гифки-блобы) - имя в предпросмотре
        // не нужно: внутри и так карточка.
        if (UUID_FILE.matches(t)) return GIF_LABEL
        // Раунд 166: подпись визитки стикера («📎 Стикер.webp (76.6 КБ)»)
        // - именно её получают уведомления.
        if (t.startsWith("\ud83d\udcce Стикер") || t.startsWith("\uD83D\uDCC8 Стикер")) {
            return "\uD83D\uDDBC Стикер"
        }
        return raw
    }
}

def sc(box):
    return tuple(v * S for v in box)


def scpts(pts):
    return [(x * S, y * S) for x, y in pts]


class G:
    """Маска глифа: белое - тело, 0 - вырезы."""

    def __init__(self):
        self.img = Image.new("L", (SIZE, SIZE), 0)
        self.d = ImageDraw.Draw(self.img)

    def e(self, box):
        self.d.ellipse(sc(box), fill=255)

    def e0(self, box):
        self.d.ellipse(sc(box), fill=0)

    def p(self, pts):
        self.d.polygon(scpts(pts), fill=255)

    def p0(self, pts):
        self.d.polygon(scpts(pts), fill=0)

    def rr(self, box, r=3):
        self.d.rounded_rectangle(sc(box), radius=r * S, fill=255)

    def rr0(self, box, r=3):
        self.d.rounded_rectangle(sc(box), radius=r * S, fill=0)

    def ln(self, a, b, w=6):
        self.d.line((a[0] * S, a[1] * S, b[0] * S, b[1] * S), fill=255,
                    width=int(w * S))

    def ln0(self, a, b, w=6):
        self.d.line((a[0] * S, a[1] * S, b[0] * S, b[1] * S), fill=0,
                    width=int(w * S))

    def ring(self, box, w=6):
        self.d.ellipse(sc(box), outline=255, width=int(w * S))

    def ring0(self, box, w=6):
        self.d.ellipse(sc(box), outline=0, width=int(w * S))

    def pie(self, box, a0, a1):
        self.d.pieslice(sc(box), a0, a1, fill=255)

    def pie0(self, box, a0, a1):
        self.d.pieslice(sc(box), a0, a1, fill=0)



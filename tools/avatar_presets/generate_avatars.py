def gradient(top, bottom):
    import numpy as np
    t = np.linspace(0.0, 1.0, SIZE)[:, None]
    col = (1 - t) * np.array(top)[None, :] + t * np.array(bottom)[None, :]
    arr = np.repeat(col[:, None, :], SIZE, axis=1).astype(np.uint8)
    return Image.fromarray(arr, "RGB")


def render(idx):
    g = G()
    GLYPHS[idx](g)
    top, bottom = GRADS[idx % len(GRADS)]
    bg = gradient(top, bottom).convert("RGBA")
    white = Image.new("RGBA", (SIZE, SIZE), (255, 255, 255, 255))
    out = Image.composite(white, bg, g.img.convert("L"))
    return out.convert("RGB")


def main():
    os.makedirs(OUT, exist_ok=True)
    thumbs = []
    for i in range(50):
        img = render(i)
        img.save(os.path.join(OUT, "avatar_std_%02d.png" % (i + 1)))
        thumbs.append(img.resize((100, 100)))
    # монтажная таблица 10x5 для просмотра
    sheet = Image.new("RGB", (10 * 108, 5 * 108), (24, 26, 34))
    for i, t in enumerate(thumbs):
        x = (i % 10) * 108 + 4
        y = (i // 10) * 108 + 4
        sheet.paste(t, (x, y))
